#!/usr/bin/env node
// Generates web/src/nick-palette.ts with perceptually-spaced OKLCH hues.
// Equal angular steps in OKLCH = equal chord distance in OKLab at fixed L/C.
// Run: node scripts/gen-nick-palette.mjs

import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dir = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dir, "../web/src/nick-palette.ts");

const COUNT = 48;
const STEP = 360 / COUNT;

const hues = Array.from({ length: COUNT }, (_, i) =>
  Number((i * STEP).toFixed(4))
);

const ts = `\
// generated by scripts/gen-nick-palette.mjs — do not edit by hand
export const NICK_HUES: readonly number[] = [
  ${hues.join(", ")},
] as const;
`;

writeFileSync(OUT, ts, "utf8");
console.log(`wrote ${OUT} (${COUNT} hues, step ${STEP}°)`);
